import { loadCheckInHistory } from '../data/checkIn'
import type { ModuleId, ParentSettings, ProgressState } from '../types'

const MODULE_NAMES: Record<ModuleId, string> = {
  abc: 'ABCs',
  shapes: 'Shapes',
  colors: 'Colors',
  numbers: 'Numbers',
  signs: 'Sign language',
  foods: 'Pictures / Foods',
}

function startOfWeek(d = new Date()) {
  const x = new Date(d)
  const day = x.getDay()
  const diff = (day + 6) % 7
  x.setHours(0, 0, 0, 0)
  x.setDate(x.getDate() - diff)
  return x
}

export function buildWeekInsightsText(
  settings: ParentSettings,
  progress: ProgressState,
  profileName: string,
) {
  const weekStart = startOfWeek()
  const checkIns = loadCheckInHistory().filter((c) => new Date(c.at) >= weekStart)
  const lines: string[] = [
    'Soft Steps — week summary',
    `Kid: ${profileName}`,
    `Week of ${weekStart.toLocaleDateString()}`,
    '',
    'Routines',
    `- Done today: ${settings.careStats.routinesCompletedToday}`,
    `- All time: ${settings.careStats.routinesCompleted}`,
    `- Tokens: ${settings.routinePrefs.tokensEarned}`,
    settings.careStats.lastRoutineAt
      ? `- Last finished: ${new Date(settings.careStats.lastRoutineAt).toLocaleString()}`
      : '- Last finished: none yet',
    '',
    'AAC check-ins this week',
  ]

  if (checkIns.length === 0) {
    lines.push('- None yet')
  } else {
    for (const c of checkIns.slice(0, 12)) {
      lines.push(
        `- ${new Date(c.at).toLocaleString()}: ${c.feelingLabel} · ${c.needLabel} — ${c.sentence}`,
      )
    }
  }

  lines.push('', 'Practice streaks')
  for (const id of Object.keys(MODULE_NAMES) as ModuleId[]) {
    const p = progress[id]
    lines.push(
      `- ${MODULE_NAMES[id]}: best ★ ${p.bestStreak} · ${p.correct}/${p.attempts || 0} correct`,
    )
  }

  lines.push(
    '',
    `Family AAC phrases: ${settings.customAacCards.length}`,
    '',
    'Generated by Soft Steps (device-local).',
  )
  return lines.join('\n')
}
